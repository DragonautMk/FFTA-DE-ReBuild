/// A literal operand and the original PC-relative LDR that can read it.
/// The word is preserved without inferring whether its bits are an address.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LiteralWord {
    pub source_offset: u32,
    pub reader_offset: u32,
    pub value: u32,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ThumbPcLiterals {
    pub literals: Vec<LiteralWord>,
    pub additional: Vec<LiteralWord>,
    pub observed: Vec<LiteralWord>,
    pub home_anchored: Vec<LiteralWord>,
    pub home_observed: Vec<LiteralWord>,
}
impl ThumbPcLiterals {
    pub fn validate(&self) -> Result<(), String> {
        if self.literals.len() != LITERAL_COUNT
            || self
                .literals
                .iter()
                .zip(LITERALS)
                .any(|(v, (offset, reader, _))| {
                    v.source_offset != offset || v.reader_offset != reader
                })
        {
            return Err("Invalid EUR Thumb literal source, reader or order".into());
        }
        if self.additional.len() != ADDITIONAL_COUNT
            || self
                .additional
                .iter()
                .zip(ADDITIONAL)
                .any(|(v, (offset, reader, _, _, _))| {
                    v.source_offset != offset || v.reader_offset != reader
                })
        {
            return Err("Invalid additional EUR Thumb literal source, reader or order".into());
        }
        if self.observed.len() != OBSERVED_COUNT
            || self
                .observed
                .iter()
                .zip(OBSERVED)
                .any(|(v, (offset, reader, _))| {
                    v.source_offset != offset || v.reader_offset != reader
                })
        {
            return Err("Invalid observed EUR Thumb literal source, reader or order".into());
        }
        if self.home_anchored.len() != HOME_ANCHORED_COUNT
            || self.home_anchored.iter().zip(HOME_ANCHORED).any(|(v, (offset, reader, _, _, _))| {
                v.source_offset != offset || v.reader_offset != reader
            })
        {
            return Err("Invalid home-anchored EUR Thumb literal source, reader or order".into());
        }
        if self.home_observed.len() != HOME_OBSERVED_COUNT
            || self.home_observed.iter().zip(HOME_OBSERVED).any(|(v, (offset, reader, _))| {
                v.source_offset != offset || v.reader_offset != reader
            })
        {
            return Err("Invalid home-observed EUR Thumb literal source, reader or order".into());
        }
        Ok(())
    }

    /// Returns a byte of one observed literal without affecting other guest reads.
    pub fn byte_at(&self, offset: u32) -> Option<(u8, usize)> {
        let base = offset & !3;
        if let Ok(index) = self
            .literals
            .binary_search_by_key(&base, |v| v.source_offset)
        {
            return Some((
                self.literals[index].value.to_le_bytes()[(offset & 3) as usize],
                index,
            ));
        }
        if let Ok(index) = self
            .additional
            .binary_search_by_key(&base, |v| v.source_offset)
        {
            return Some((
                self.additional[index].value.to_le_bytes()[(offset & 3) as usize],
                LITERAL_COUNT + index,
            ));
        }
        if let Ok(index) = self.observed.binary_search_by_key(&base, |v| v.source_offset) {
            return Some((self.observed[index].value.to_le_bytes()[(offset & 3) as usize], LITERAL_COUNT + ADDITIONAL_COUNT + index));
        }
        if let Ok(index) = self.home_anchored.binary_search_by_key(&base, |v| v.source_offset) {
            return Some((self.home_anchored[index].value.to_le_bytes()[(offset & 3) as usize], LITERAL_COUNT + ADDITIONAL_COUNT + OBSERVED_COUNT + index));
        }
        let index = self.home_observed.binary_search_by_key(&base, |v| v.source_offset).ok()?;
        Some((self.home_observed[index].value.to_le_bytes()[(offset & 3) as usize], LITERAL_COUNT + ADDITIONAL_COUNT + OBSERVED_COUNT + HOME_ANCHORED_COUNT + index))
    }

    pub fn verify_source(&self, rom: &[u8]) -> Result<(), String> {
        self.validate()?;
        if self != &Catalog::from_rom(rom, &[])?.decoded {
            return Err("Thumb literals differ from authenticated EUR source".into());
        }
        Ok(())
    }
}

pub struct Catalog {
    pub decoded: ThumbPcLiterals,
    pub sources: Vec<SourceRange>,
}
impl Catalog {
    pub fn from_rom(rom: &[u8], previous: &[Resource]) -> Result<Self, String> {
        if rom.len() != 0x0100_0000 || ffta_rom::digest(rom) != ffta_rom::EUROPE_SHA256 {
            return Err("Thumb literals require exact EUR ROM; USA pending".into());
        }
        let prior = PriorSources::new(previous)?;
        let mut literals = Vec::with_capacity(LITERAL_COUNT);
        let mut sources = Vec::with_capacity(LITERAL_COUNT + ADDITIONAL_COUNT + OBSERVED_COUNT + HOME_ANCHORED_COUNT + HOME_OBSERVED_COUNT);
        for (offset, reader, expected_opcode) in LITERALS {
            let at = reader as usize;
            let opcode = u16::from_le_bytes(rom[at..at + 2].try_into().unwrap());
            if offset & 3 != 0
                || opcode != expected_opcode
                || opcode & 0xf800 != 0x4800
                || ((reader + 4) & !3) + u32::from(opcode & 255) * 4 != offset
            {
                return Err("Thumb literal reader or source address mismatch".into());
            }
            let bytes = &rom[offset as usize..offset as usize + 4];
            if prior.contains(offset, bytes.len())? {
                return Err("Thumb literal already has an owner".into());
            }
            literals.push(LiteralWord {
                source_offset: offset,
                reader_offset: reader,
                value: u32::from_le_bytes(bytes.try_into().unwrap()),
            });
            sources.push(SourceRange {
                offset,
                length: 4,
                sha256: ffta_rom::digest(bytes),
                role: SOURCE_ROLE.into(),
            });
        }
        let mut additional = Vec::with_capacity(ADDITIONAL_COUNT);
        for (offset, reader, expected_opcode, anchor, expected_path_sha256) in ADDITIONAL {
            let at = reader as usize;
            let opcode = u16::from_le_bytes(rom[at..at + 2].try_into().unwrap());
            if offset & 3 != 0
                || opcode != expected_opcode
                || opcode & 0xf800 != 0x4800
                || ((reader + 4) & !3) + u32::from(opcode & 255) * 4 != offset
                || anchor > reader
                || reader - anchor > 96
                || (reader - anchor) & 1 != 0
                || ffta_rom::digest(&rom[anchor as usize..at + 2]) != expected_path_sha256
                || (anchor..reader).step_by(2).any(|pc| {
                    let at = pc as usize;
                    !straight_line_thumb(u16::from_le_bytes(rom[at..at + 2].try_into().unwrap()))
                })
                || LITERALS.binary_search_by_key(&offset, |v| v.0).is_ok()
            {
                return Err("Additional Thumb literal reader or anchor mismatch".into());
            }
            let bytes = &rom[offset as usize..offset as usize + 4];
            if prior.contains(offset, bytes.len())? {
                return Err("Additional Thumb literal already has an owner".into());
            }
            additional.push(LiteralWord {
                source_offset: offset,
                reader_offset: reader,
                value: u32::from_le_bytes(bytes.try_into().unwrap()),
            });
            sources.push(SourceRange {
                offset,
                length: 4,
                sha256: ffta_rom::digest(bytes),
                role: SOURCE_ROLE.into(),
            });
        }
        let mut observed = Vec::with_capacity(OBSERVED_COUNT);
        for (offset, reader, expected_opcode) in OBSERVED {
            let at = reader as usize;
            let opcode = u16::from_le_bytes(rom[at..at + 2].try_into().unwrap());
            if offset & 3 != 0
                || opcode != expected_opcode
                || opcode & 0xf800 != 0x4800
                || ((reader + 4) & !3) + u32::from(opcode & 255) * 4 != offset
                || LITERALS.binary_search_by_key(&offset, |v| v.0).is_ok()
                || ADDITIONAL.binary_search_by_key(&offset, |v| v.0).is_ok()
            {
                return Err("Observed Thumb literal reader or source address mismatch".into());
            }
            let bytes = &rom[offset as usize..offset as usize + 4];
            if prior.contains(offset, bytes.len())? {
                return Err("Observed Thumb literal already has an owner".into());
            }
            observed.push(LiteralWord {
                source_offset: offset,
                reader_offset: reader,
                value: u32::from_le_bytes(bytes.try_into().unwrap()),
            });
            sources.push(SourceRange {
                offset,
                length: 4,
                sha256: ffta_rom::digest(bytes),
                role: SOURCE_ROLE.into(),
            });
        }
        let mut home_anchored = Vec::with_capacity(HOME_ANCHORED_COUNT);
        for (offset, reader, expected_opcode, anchor, expected_path_sha256) in HOME_ANCHORED {
            let at = reader as usize;
            let opcode = u16::from_le_bytes(rom[at..at + 2].try_into().unwrap());
            if offset & 3 != 0
                || opcode != expected_opcode
                || opcode & 0xf800 != 0x4800
                || ((reader + 4) & !3) + u32::from(opcode & 255) * 4 != offset
                || anchor > reader || reader - anchor > 96 || (reader - anchor) & 1 != 0
                || ffta_rom::digest(&rom[anchor as usize..at + 2]) != expected_path_sha256
                || (anchor..reader).step_by(2).any(|pc| {
                    let at = pc as usize;
                    !straight_line_thumb(u16::from_le_bytes(rom[at..at + 2].try_into().unwrap()))
                })
                || LITERALS.binary_search_by_key(&offset, |v| v.0).is_ok()
                || ADDITIONAL.binary_search_by_key(&offset, |v| v.0).is_ok()
                || OBSERVED.binary_search_by_key(&offset, |v| v.0).is_ok()
            {
                return Err("Home-anchored Thumb literal reader or source mismatch".into());
            }
            let bytes = &rom[offset as usize..offset as usize + 4];
            if prior.contains(offset, bytes.len())? {
                return Err("Home-anchored Thumb literal already has an owner".into());
            }
            home_anchored.push(LiteralWord { source_offset: offset, reader_offset: reader,
                value: u32::from_le_bytes(bytes.try_into().unwrap()) });
            sources.push(SourceRange { offset, length: 4, sha256: ffta_rom::digest(bytes), role: SOURCE_ROLE.into() });
        }
        let mut home_observed = Vec::with_capacity(HOME_OBSERVED_COUNT);
        for (offset, reader, expected_opcode) in HOME_OBSERVED {
            let at = reader as usize;
            let opcode = u16::from_le_bytes(rom[at..at + 2].try_into().unwrap());
            if offset & 3 != 0 || opcode != expected_opcode || opcode & 0xf800 != 0x4800
                || ((reader + 4) & !3) + u32::from(opcode & 255) * 4 != offset
                || LITERALS.binary_search_by_key(&offset, |v| v.0).is_ok()
                || ADDITIONAL.binary_search_by_key(&offset, |v| v.0).is_ok()
                || OBSERVED.binary_search_by_key(&offset, |v| v.0).is_ok()
                || HOME_ANCHORED.binary_search_by_key(&offset, |v| v.0).is_ok()
            {
                return Err("Home-observed Thumb literal reader or source mismatch".into());
            }
            let bytes = &rom[offset as usize..offset as usize + 4];
            if prior.contains(offset, bytes.len())? {
                return Err("Home-observed Thumb literal already has an owner".into());
            }
            home_observed.push(LiteralWord { source_offset: offset, reader_offset: reader,
                value: u32::from_le_bytes(bytes.try_into().unwrap()) });
            sources.push(SourceRange { offset, length: 4, sha256: ffta_rom::digest(bytes), role: SOURCE_ROLE.into() });
        }
        let decoded = ThumbPcLiterals {
            literals,
            additional,
            observed,
            home_anchored,
            home_observed,
        };
        decoded.validate()?;
        Ok(Self { decoded, sources })
    }
}

/// Conservative straight-line check for the statically anchored reader window.
fn straight_line_thumb(hw: u16) -> bool {
    if hw & 0xf000 == 0xd000
        || matches!(hw & 0xf800, 0xe000 | 0xf000 | 0xf800)
        || matches!(hw & 0xff00, 0xbd00 | 0xbe00)
    {
        return false;
    }
    if hw & 0xfc00 == 0x4400 {
        let op = (hw >> 8) & 3;
        let rd = (hw & 7) | ((hw >> 4) & 8);
        if op == 3 || (rd == 15 && (op == 0 || op == 2)) {
            return false;
        }
    }
    !(hw & 0xf000 == 0xb000 && !matches!(hw & 0xff00, 0xb000 | 0xb400 | 0xb500 | 0xbc00 | 0xbd00))
}

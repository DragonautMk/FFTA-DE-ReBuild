/// Conservative straight-line check for the statically anchored reader window.
fn straight_line_thumb(hw: u16) -> bool {
    if hw & 0xf000 == 0xd000
        || matches!(hw & 0xf800, 0xe000 | 0xf000 | 0xf800)
        || matches!(hw & 0xff00, 0xbd00 | 0xbe00)
    {
        return false;
    }
    if hw & 0xfc00 == 0x4400 {
        let op = (hw >> 8) & 3;
        let rd = (hw & 7) | ((hw >> 4) & 8);
        if op == 3 || (rd == 15 && (op == 0 || op == 2)) {
            return false;
        }
    }
    !(hw & 0xf000 == 0xb000 && !matches!(hw & 0xff00, 0xb000 | 0xb400 | 0xb500 | 0xbc00 | 0xbd00))
}

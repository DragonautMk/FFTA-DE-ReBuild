pub(super) fn validate(words: &[LiteralWord]) -> Result<(), String> {
    if words.is_empty() {
        return Ok(());
    }
    if words.len() != LOADS.len()
        || words.iter().zip(LOADS).any(|(word, (source, reader, _))| {
            word.source_offset != source || word.reader_offset != reader
        })
    {
        return Err("Invalid title frontend literal sources or readers".into());
    }
    let bytes: Vec<_> = words
        .iter()
        .flat_map(|word| word.value.to_le_bytes())
        .collect();
    if ffta_rom::digest(&bytes) != SOURCE_SHA256 {
        return Err("Title frontend literal fingerprint mismatch".into());
    }
    Ok(())
}

pub(super) fn extract(rom: &[u8]) -> Result<Vec<LiteralWord>, String> {
    if ffta_rom::digest(&rom[0x139508..0x13ba90]) != FRONTEND_SHA256 {
        return Err("Title frontend instruction fingerprint mismatch".into());
    }
    let words = LOADS
        .into_iter()
        .map(|(source, reader, opcode)| LiteralWord::from_thumb_load(rom, source, reader, opcode))
        .collect::<Result<Vec<_>, String>>()?;
    validate(&words)?;
    Ok(words)
}

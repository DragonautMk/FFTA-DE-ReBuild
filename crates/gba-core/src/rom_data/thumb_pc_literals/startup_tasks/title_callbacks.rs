pub(super) fn verify_windows(rom: &[u8]) -> Result<(), String> {
    for (start, end, expected) in CALLBACK_WINDOWS {
        if ffta_rom::digest(&rom[start..end]) != expected {
            return Err(format!(
                "Title callback fingerprint mismatch at {start:06x}"
            ));
        }
    }
    Ok(())
}
